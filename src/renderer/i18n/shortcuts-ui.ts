type Copy = typeof shortcutLocales['zh-CN']
type Key = `shortcuts.${Exclude<keyof Copy, 'actions'> | `actions.${keyof Copy['actions']}`}`
export function shortcutEntries(copy: Copy): Record<Key, string> {
  const entries: Array<[string, string]> = []
  for (const [key, value] of Object.entries(copy)) {
    if (typeof value === 'string') entries.push([`shortcuts.${key}`, value])
    else for (const [action, text] of Object.entries(value)) entries.push([`shortcuts.${key}.${action}`, text])
  }
  return Object.fromEntries(entries) as Record<Key, string>
}
